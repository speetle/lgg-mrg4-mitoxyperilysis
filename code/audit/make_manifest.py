#!/usr/bin/env python3
"""Regenerate the integrity manifests and the supplementary-table index.

v1.0.0 shipped the manifests without the script that produced them, so a file
added by hand could leave the release inconsistent. This script derives all three
index files from the tree on disk:

    data/_补充表清单.md      per-table byte count and SHA-256
    data/SHA256SUMS.txt     every file under data/ except the manifest itself
    SHA256SUMS.txt          every file in the release except the manifest itself

Run it from anywhere, then verify with ``shasum -a 256 -c``::

    python code/audit/make_manifest.py
    shasum -a 256 -c SHA256SUMS.txt
    (cd data && shasum -a 256 -c SHA256SUMS.txt)

The order of the generated files matters: the index of supplementary tables is
hashed by ``data/SHA256SUMS.txt``, which is hashed by the root manifest. The
script writes them in that order for that reason.
"""
from __future__ import annotations

import hashlib
import os
import sys

SKIP_DIRS = {".git", "__pycache__", ".ipynb_checkpoints"}
SKIP_NAMES = {".DS_Store"}


def sha256(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def walk(root: str) -> list[str]:
    """Every file under *root*, as paths relative to the repository root."""
    out = []
    for base, dirs, files in os.walk(root):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS)
        for name in sorted(files):
            if name in SKIP_NAMES or name.endswith(".pyc"):
                continue
            rel = os.path.join(base, name).replace(os.sep, "/")
            out.append(rel[2:] if rel.startswith("./") else rel)
    return sorted(out)


def main() -> int:
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    os.chdir(root)

    data_files = [f for f in walk("data") if f != "data/SHA256SUMS.txt"]
    tables = [f for f in data_files if os.path.basename(f).startswith("Table_")]

    # 1. index of supplementary tables (lists tables only, never itself)
    lines = [
        "# 补充材料清单",
        "",
        "校验：`cd data && shasum -a 256 -c SHA256SUMS.txt`（应全部 OK）。",
        "",
        f"清单覆盖 **{len(tables)} 个沉积表**。",
        "本文件与 `SHA256SUMS.txt` 是两个索引件，**不把自己算进校验**（自指无意义）。",
        "SHAs are generated by `code/audit/make_manifest.py`; do not edit by hand.",
        "",
        "| 文件 | 字节 | SHA-256 |",
        "|---|---|---|",
    ]
    for f in tables:
        lines.append(f"| `{os.path.basename(f)}` | {os.path.getsize(f)} | `{sha256(f)}` |")
    with open("data/_补充表清单.md", "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    # 2. data manifest
    with open("data/SHA256SUMS.txt", "w", encoding="utf-8") as fh:
        for f in data_files:
            fh.write(f"{sha256(f)}  {f[len('data/'):]}\n")

    # 3. root manifest
    root_files = [f for f in walk(".") if f != "SHA256SUMS.txt"]
    with open("SHA256SUMS.txt", "w", encoding="utf-8") as fh:
        for f in root_files:
            fh.write(f"{sha256(f)}  {f}\n")

    print(f"data/_补充表清单.md   {len(tables)} tables")
    print(f"data/SHA256SUMS.txt   {len(data_files)} files")
    print(f"SHA256SUMS.txt        {len(root_files)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
